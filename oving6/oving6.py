def fBlock(i, j):
    if (i, j) in [(2, 3), (2, 5), (3, 6), (4, 2), (5, 4)]:
        return 0

    if i == 1 or j == 1:
        return 1

    return fBlock(i - 1, j) + fBlock(i, j - 1)

